#!/usr/bin/env bash
# Build <KMI>_kernelsu.ko and <KMI>_susfs_guard_lkm.ko from official DDK GKI images
# and install them into userspace/ksud/bin/aarch64/ (embedded by rust-embed).
#
# Usage: scripts/build_kmi.sh <kmi>       e.g. scripts/build_kmi.sh android15-6.6
# Env:
#   CLANG_BIN   clang toolchain bin dir (default /usr/lib/llvm-18/bin)
#   KDIR, SRC   override extracted KDIR / kernel source dirs
#   DDK_PREBUILTS  ddk-prebuilts git-lfs repo (default /root/ddk-prebuilts)
#   SUSFS_SRC   susfs4ksu-lkm source (default /root/susfs-lkm-src)
#   KSU_EXPECTED_SIZE / KSU_EXPECTED_HASH  manager cert values
#   KEEP=1      keep extracted KDIR/SRC after a successful build
set -euo pipefail

T=${1:?usage: $0 <kmi>  e.g. android15-6.6}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
CLANG_BIN=${CLANG_BIN:-/usr/lib/llvm-18/bin}
export PATH="$CLANG_BIN:$PATH"
DDK_WORK=${DDK_WORK:-/opt/ddk}
LOGDIR=${KMI_LOGDIR:-${TMPDIR:-/tmp}/nekosu-kmi}
mkdir -p "$LOGDIR"
PB=${DDK_PREBUILTS:-/root/ddk-prebuilts}
KDIR=${KDIR:-$DDK_WORK/kdir/$T}
SRC=${SRC:-$DDK_WORK/src/$T}
SUSFS_SRC=${SUSFS_SRC:-/root/susfs-lkm-src}
SIZE=${KSU_EXPECTED_SIZE:?set KSU_EXPECTED_SIZE}
HASH=${KSU_EXPECTED_HASH:?set KSU_EXPECTED_HASH}
KVER=${T##*-}; KMAJ=${KVER%%.*}; KMIN=${KVER#*.}
NEW_STYLE=0
{ [ "$KMAJ" -gt 6 ] || { [ "$KMAJ" -eq 6 ] && [ "$KMIN" -ge 12 ]; }; } && NEW_STYLE=1
echo "[$T] kernel $KMAJ.$KMIN, new-style kbuild=$NEW_STYLE"

# 1) fetch official images (git-lfs) and extract (skipped inside DDK images)
if [ "${SKIP_PREBUILT_FETCH:-0}" = "1" ]; then
  [ -f "$KDIR/Makefile" ] || {
    echo "FAIL: SKIP_PREBUILT_FETCH=1 but KDIR missing ($KDIR)"; exit 1; }
  # ddk-min images may only ship KDIR; recover the source path from its wrapper
  if [ ! -f "$SRC/Makefile" ]; then
    INC=$(sed -n 's/^include //p' "$KDIR/Makefile" 2>/dev/null | head -1)
    [ -n "$INC" ] && SRC=$(dirname "$INC")
  fi
  [ -f "$SRC/Makefile" ] || SRC="$KDIR"
  echo "[$T] using prebuilt KDIR/SRC from DDK image: KDIR=$KDIR SRC=$SRC"
else
cd "$PB"
for f in "kdir-min/kdir.$T.tar.zst" "src/src.$T.tar.zst"; do
  if [ "$(stat -c%s "$f" 2>/dev/null || echo 0)" -lt 1000000 ]; then
    echo "[$T] pulling $f"
    git lfs pull --include="$f" >/dev/null 2>&1 || true
    git lfs fetch origin --include="$f" >/dev/null 2>&1 || true
    git lfs checkout "$f" >/dev/null 2>&1 || true
  fi
  [ "$(stat -c%s "$f" 2>/dev/null || echo 0)" -gt 1000000 ] || { echo "FAIL: cannot fetch $f (need git-lfs + network)"; exit 1; }
done
if [ ! -f "$KDIR/Makefile" ] || [ ! -f "$SRC/Makefile" ]; then
  rm -rf "$KDIR" "$SRC"; mkdir -p "$KDIR" "$SRC"
  tar --zstd -xf "kdir-min/kdir.$T.tar.zst" -C "$KDIR"
  tar --zstd -xf "src/src.$T.tar.zst" -C "$SRC"
  for d in "$KDIR" "$SRC"; do
    if [ -d "$d/$T" ]; then mv "$d/$T" "$d.tmp"; rmdir "$d"; mv "$d.tmp" "$d"; fi
  done
fi
# The official kdir tarball ships a wrapper Makefile that points at the
# maintainer's absolute source path; repoint it at this checkout.
if [ -f "$KDIR/Makefile" ] && head -n1 "$KDIR/Makefile" | grep -q "Automatically generated"; then
  printf '# regenerated by build_kmi.sh\ninclude %s/Makefile\n' "$SRC" > "$KDIR/Makefile"
fi
fi
echo "[$T] kdir=$(du -sh "$KDIR" | cut -f1) src=$(du -sh "$SRC" | cut -f1)"

# 2) remove x86_64 prebuilt host artifacts so they are rebuilt natively
for tree in "$KDIR" "$SRC"; do
  while IFS= read -r f; do
    case "$(file -b "$f" 2>/dev/null)" in *x86-64*|*x86_64*) rm -f "$f";; esac
  done < <(find "$tree/scripts" "$tree/tools" -type f \( -name '*.o' -o -perm -111 \) 2>/dev/null)
done

# 3) 6.12 modpost: with no unresolved symbols it emits
#      __used __section("__version_ext_names") =
#      ;
#    which is invalid C. Emit `= ""` so the empty case is valid and symbol
#    names still concatenate as adjacent string literals.
if [ "$NEW_STYLE" = "1" ]; then
  python3 - "$SRC/scripts/mod/modpost.c" <<'PY'
import sys
p = sys.argv[1]
s = open(p).read()
old = 'buf_printf(b, "__used __section(\\"__version_ext_names\\") =\\n");'
new = 'buf_printf(b, "__used __section(\\"__version_ext_names\\") = \\"\\"\\n");'
if old in s:
    open(p, "w").write(s.replace(old, new, 1))
    print("patched modpost.c")
else:
    print("modpost.c already patched or format changed")
PY
fi

# clean stale in-tree generated module artifacts from previous manual builds
rm -f "$ROOT"/kernel/kernelsu.mod.c "$ROOT"/kernel/kernelsu.mod \
      "$ROOT"/kernel/kernelsu.o "$ROOT"/kernel/kernelsu.ko \
      "$ROOT"/kernel/modules.order "$ROOT"/kernel/.module-common.o \
      "$ROOT"/kernel/compat/syscall_no.h 2>/dev/null || true
rm -f "$ROOT/out/kmi-$T/compat/syscall_no.h" "$ROOT/out/kmi-$T/kernelsu.mod.c" 2>/dev/null || true

# 4) native host tools
make -C "$KDIR" ARCH=arm64 LLVM=1 LLVM_IAS=1 olddefconfig </dev/null > $LOGDIR/kmi-$T-tools.log 2>&1 || true
make -C "$KDIR" ARCH=arm64 LLVM=1 LLVM_IAS=1 modules_prepare >> $LOGDIR/kmi-$T-tools.log 2>&1 || true
[ -x "$KDIR/scripts/mod/modpost" ] || make -C "$KDIR" ARCH=arm64 LLVM=1 LLVM_IAS=1 scripts >> $LOGDIR/kmi-$T-tools.log 2>&1 || true
[ -x "$KDIR/scripts/mod/modpost" ] && [ -x "$KDIR/scripts/basic/fixdep" ] || { echo "FAIL host tools"; tail -20 $LOGDIR/kmi-$T-tools.log; exit 1; }

# 4b) disable BTF module generation (resolve_btfids host tool is not built here;
# our modules do not need BTF and it would only add an extra host dependency)
if [ -f "$SRC/scripts/config" ]; then
  "$SRC/scripts/config" --file "$KDIR/.config" -d DEBUG_INFO_BTF -d DEBUG_INFO_BTF_MODULES >/dev/null 2>&1 || true
  make -C "$KDIR" ARCH=arm64 LLVM=1 LLVM_IAS=1 syncconfig </dev/null >/dev/null 2>&1 || true
  make -C "$KDIR" ARCH=arm64 LLVM=1 LLVM_IAS=1 olddefconfig </dev/null >/dev/null 2>&1 || true
fi

# 4c) generate kernel headers (asm/unistd_compat_32.h etc. are produced by
# prepare/headers targets; module builds do not trigger them on their own)
make -C "$KDIR" ARCH=arm64 LLVM=1 LLVM_IAS=1 prepare >> "$LOGDIR/kmi-$T-tools.log" 2>&1 || true
make -C "$KDIR" ARCH=arm64 LLVM=1 LLVM_IAS=1 headers_install INSTALL_HDR_PATH="$KDIR/usr" >> "$LOGDIR/kmi-$T-tools.log" 2>&1 || true

# 5) clean stale artifacts in susfs module source
rm -rf "$SUSFS_SRC/kernel/modules.order" "$SUSFS_SRC/kernel/Module.symvers" \
       "$SUSFS_SRC/kernel/.tmp_versions" "$SUSFS_SRC/kernel/.module-common.o" 2>/dev/null || true
( cd "$SUSFS_SRC/kernel" && rm -f *.o *.ko *.mod *.mod.c .*.cmd 2>/dev/null || true )

# 6) build kernelsu.ko (empty Module.symvers => empty __versions, loader binds via kallsyms)
cd "$ROOT"
SYMVERS_BAK=$(mktemp "${TMPDIR:-/tmp}/nekosu-symvers.XXXXXX")
cp -f "$KDIR/Module.symvers" "$SYMVERS_BAK"
: > "$KDIR/Module.symvers"
OUT="$ROOT/out/kmi-$T"; rm -rf "$OUT"; mkdir -p "$OUT"
KSU_ARGS=(CONFIG_KSU=m CONFIG_KSU_TRACEPOINT_HOOK=y CONFIG_KSU_MULTI_MANAGER_SUPPORT=y
          KSU_EXPECTED_SIZE="$SIZE" KSU_EXPECTED_HASH="$HASH"
          KBUILD_MODPOST_WARN=1)
if [ "$NEW_STYLE" = "1" ]; then
  KSU_ARGS+=(KSU_SKIP_PREINIT=1)
else
  # old Kbuild: empty BTF vars are enough to skip resolve_btfids
  KSU_ARGS+=(CONFIG_DEBUG_INFO_BTF_MODULES= CONFIG_DEBUG_INFO_BTF=)
fi
set +e
if [ "$NEW_STYLE" = "1" ]; then
  env "${KSU_ARGS[@]}" make -C "$KDIR" M="$ROOT/kernel" MO="$OUT" ARCH=arm64 LLVM=1 LLVM_IAS=1 \
    modules -j"$(nproc)" > $LOGDIR/kmi-$T-ko.log 2>&1
else
  env "${KSU_ARGS[@]}" make -C "$KDIR" M="$OUT" src="$ROOT/kernel" ARCH=arm64 LLVM=1 LLVM_IAS=1 \
    modules -j"$(nproc)" > $LOGDIR/kmi-$T-ko.log 2>&1
fi
RC=$?; set -e
cp -f "$SYMVERS_BAK" "$KDIR/Module.symvers"
if [ $RC -ne 0 ]; then echo "FAIL kernelsu ($T)"; grep -E "error:|fatal error" $LOGDIR/kmi-$T-ko.log | head -8; tail -5 $LOGDIR/kmi-$T-ko.log; exit 1; fi
KO=""
for f in "$ROOT/kernel/kernelsu.ko" "$OUT/kernelsu.ko"; do
  [ -f "$f" ] && { KO="$f"; break; }
done
[ -n "$KO" ] || { echo "FAIL: kernelsu.ko not found"; exit 1; }
echo "[$T] KSU: $(strings "$KO" | grep -m1 '^vermagic=')"
"$CLANG_BIN/llvm-strip" -d "$KO"
mkdir -p "$ROOT/userspace/ksud/bin/aarch64"
cp -f "$KO" "$ROOT/userspace/ksud/bin/aarch64/${T}_kernelsu.ko"
# clean source-dir artifacts produced by new-style build
( cd "$ROOT/kernel" && rm -f kernelsu.mod.c kernelsu.mod.o .module-common.o kernelsu.ko 2>/dev/null || true )

# 7) build SUSFS LKM against the same KDIR
SOUT="$ROOT/out/susfs-$T"; rm -rf "$SOUT"; mkdir -p "$SOUT"
set +e
if [ "$NEW_STYLE" = "1" ]; then
  make -C "$KDIR" M="$SUSFS_SRC/kernel" MO="$SOUT" ARCH=arm64 LLVM=1 LLVM_IAS=1 \
    KBUILD_MODPOST_WARN=1 modules -j"$(nproc)" > $LOGDIR/kmi-$T-susfs.log 2>&1
else
  make -C "$KDIR" M="$SUSFS_SRC/kernel" ARCH=arm64 LLVM=1 LLVM_IAS=1 \
    KBUILD_MODPOST_WARN=1 modules -j"$(nproc)" \
    CONFIG_DEBUG_INFO_BTF_MODULES= CONFIG_DEBUG_INFO_BTF= > $LOGDIR/kmi-$T-susfs.log 2>&1
fi
RC=$?; set -e
if [ $RC -ne 0 ]; then
  echo "WARN susfs ($T) failed"; grep -E "error:|fatal error" $LOGDIR/kmi-$T-susfs.log | head -8
else
  SKO=""
  for f in "$SOUT/susfs_guard_lkm.ko" "$SUSFS_SRC/kernel/susfs_guard_lkm.ko"; do
    [ -f "$f" ] && { SKO="$f"; break; }
  done
  echo "[$T] SUSFS: $(strings "$SKO" | grep -m1 '^vermagic=')"
  "$CLANG_BIN/llvm-strip" -d "$SKO"
  cp -f "$SKO" "$ROOT/userspace/ksud/bin/aarch64/${T}_susfs_guard_lkm.ko"
fi

# 8) cleanup
if [ "${KEEP:-0}" != "1" ]; then rm -rf "$KDIR" "$SRC"; fi
ls -l --block-size=1 "$ROOT/userspace/ksud/bin/aarch64/${T}"*.ko 2>/dev/null || true
echo "[$T] DONE"
